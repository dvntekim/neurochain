"""The front end as an ngspice circuit: netlists, a runner and output parsing.

Netlists are generated from the same parameter objects the analytic model
uses, so the two cannot drift apart silently. Three reference netlists are
written to ``spice/`` for reading and for running by hand
(``ngspice -b spice/frontend.cir``); a test keeps them identical to what this
module generates.

How the circuit elements map to SPICE:

* **Electrode.** ``Rs`` in series with ``Rct`` in parallel with the double
  layer. An ideal double layer is one capacitor. A constant-phase double layer
  is the RC ladder from :func:`neurochain.frontend.electrode.cpe_ladder`. The
  ladder is passive, so SPICE's noise analysis gives it the thermal noise of
  its real part without being told.
* **OTA.** A voltage-controlled current source ``gm`` with an output resistor
  marked ``noisy=0`` (it models finite gain and must not add noise of its own).
* **OTA noise.** A resistor ``Rn`` in series with the OTA input. No current
  flows into that input, so ``Rn`` changes nothing except to add ``4kT Rn`` of
  voltage noise.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import numpy as np

from neurochain.frontend.electrode import ComplexArray, Electrode, cpe_ladder
from neurochain.frontend.model import SPIKE_BAND_HZ, FrontEnd
from neurochain.recording import FloatArray

NGSPICE = "ngspice"
NoiseSources = Literal["all", "electrode", "lna"]

IMPEDANCE_FILE = "impedance.spice.txt"
AC_FILE = "ac.spice.txt"
NOISE_FILE = "noise.spice.txt"


class SpiceError(RuntimeError):
    """ngspice is missing, failed, or produced output that could not be read."""


def ngspice_available() -> bool:
    """Return whether an ``ngspice`` executable is on the path."""
    return shutil.which(NGSPICE) is not None


def _value(x: float) -> str:
    """Format a component value with nine significant figures."""
    return f"{x:.9g}"


def _resistor(name: str, a: str, b: str, ohms: float, *, noisy: bool = True) -> str:
    return f"{name} {a} {b} {_value(ohms)}" + ("" if noisy else " noisy=0")


def electrode_elements(
    electrode: Electrode, tissue: str = "tissue", pad: str = "pad", *, noisy: bool = True
) -> list[str]:
    """Return the netlist lines for an electrode between two nodes."""
    lines = [
        f"* {electrode.name}: Rs, then Rct in parallel with the double layer",
        _resistor("Rs", tissue, "iface", electrode.rs_ohm, noisy=noisy),
        _resistor("Rct", "iface", pad, electrode.rct_ohm, noisy=noisy),
    ]
    if electrode.is_ideal_capacitor:
        lines.append(f"Cdl iface {pad} {_value(electrode.q_s_sn)}")
        return lines
    ladder = cpe_ladder(electrode.q_s_sn, electrode.n)
    lines += [
        f"* Constant-phase element Q={_value(electrode.q_s_sn)} n={electrode.n:g} as an RC ladder",
        _resistor("Rlow", "iface", pad, ladder.r_low_ohm, noisy=noisy),
        f"Chigh iface {pad} {_value(ladder.c_high_f)}",
    ]
    for i, (r, c) in enumerate(zip(ladder.branch_r_ohm, ladder.branch_c_f, strict=True)):
        lines.append(_resistor(f"Rb{i}", "iface", f"b{i}", float(r), noisy=noisy))
        lines.append(f"Cb{i} b{i} {pad} {_value(float(c))}")
    return lines


def _options(temperature_k: float) -> str:
    return f".options temp={_value(temperature_k - 273.15)} tnom=27"


def impedance_netlist(
    electrode: Electrode,
    *,
    start_hz: float = 1.0,
    stop_hz: float = 1.0e4,
    points_per_decade: int = 20,
    temperature_k: float = 310.15,
) -> str:
    """Return a netlist that sweeps the electrode's impedance.

    A 1 A AC current source drives the electrode, so the voltage across it is
    numerically its impedance in ohms.
    """
    lines = [
        f"* NeuroChain U1: impedance of {electrode.name}",
        "* Generated by neurochain.frontend.spice; do not edit by hand.",
        _options(temperature_k),
        "Itest 0 tissue dc 0 ac 1",
        *electrode_elements(electrode, pad="0"),
        ".control",
        "set wr_singlescale",
        "set wr_vecnames",
        f"ac dec {points_per_decade} {_value(start_hz)} {_value(stop_hz)}",
        f"wrdata {IMPEDANCE_FILE} v(tissue)",
        "quit",
        ".endc",
        ".end",
    ]
    return "\n".join(lines) + "\n"


def frontend_netlist(
    frontend: FrontEnd,
    *,
    sources: NoiseSources = "all",
    noise_band_hz: tuple[float, float] = SPIKE_BAND_HZ,
    ac_range_hz: tuple[float, float] = (1.0e-2, 1.0e6),
) -> str:
    """Return a netlist for the electrode and amplifier: AC sweep and noise analysis.

    Args:
        frontend: The front end to simulate.
        sources: Which elements generate noise. ``"electrode"`` and ``"lna"``
            silence the other group, which is how a simulator is made to report
            one contribution at a time.
        noise_band_hz: Band the noise analysis integrates over.
        ac_range_hz: Range of the AC sweep.
    """
    lna = frontend.lna
    temperature_k = frontend.temperature_k
    noisy_electrode = sources in ("all", "electrode")
    noisy_lna = sources in ("all", "lna")
    lines = [
        "* NeuroChain U1: electrode and capacitive-feedback amplifier",
        "* Generated by neurochain.frontend.spice; do not edit by hand.",
        f"* Noise sources enabled: {sources}",
        _options(temperature_k),
        "Vsig tissue 0 dc 0 ac 1",
    ]
    if frontend.electrode is None:
        lines.append("* Ideal source: the signal drives the coupling capacitor directly")
        pad = "tissue"
    else:
        lines += electrode_elements(frontend.electrode, noisy=noisy_electrode)
        pad = "pad"
    lines += [
        "* Capacitive feedback network: gain C1/C2, high-pass corner 1/(2 pi R2 C2)",
        f"C1 {pad} x {_value(lna.c1_f)}",
        f"Cin x 0 {_value(lna.c_in_f)}",
        f"C2 x out {_value(lna.c2_f)}",
        _resistor("R2", "x", "out", lna.r2_ohm, noisy=noisy_lna),
        "* OTA: input noise as a series resistor, then gm into Ro and CL",
        _resistor("Rn", "x", "g", lna.ota_noise_resistance_ohm(temperature_k), noisy=noisy_lna),
        f"Gota out 0 g 0 {_value(lna.gm_s(temperature_k))}",
        _resistor("Ro", "out", "0", lna.r_out_ohm(temperature_k), noisy=False),
        f"CL out 0 {_value(lna.c_load_f)}",
        ".control",
        "set wr_singlescale",
        "set wr_vecnames",
        f"ac dec 20 {_value(ac_range_hz[0])} {_value(ac_range_hz[1])}",
        f"wrdata {AC_FILE} v(out)",
        f"noise v(out) Vsig dec 200 {_value(noise_band_hz[0])} {_value(noise_band_hz[1])}",
        "print inoise_total onoise_total",
        "setplot noise1",
        f"wrdata {NOISE_FILE} inoise_spectrum onoise_spectrum",
        "quit",
        ".endc",
        ".end",
    ]
    return "\n".join(lines) + "\n"


def run_ngspice(netlist: str, files: tuple[str, ...]) -> tuple[dict[str, FloatArray], str]:
    """Run a netlist in batch mode and read the tables it writes.

    Args:
        netlist: Complete netlist text, including its ``.control`` section.
        files: Names of the ``wrdata`` files the netlist writes.

    Returns:
        ``(tables, log)``: each file as a 2-D array (first column is
        frequency), and ngspice's standard output.

    Raises:
        SpiceError: If ngspice is not installed, exits with an error or does
            not write an expected file.
    """
    if not ngspice_available():
        raise SpiceError("ngspice is not installed (macOS: `brew install ngspice`)")
    with tempfile.TemporaryDirectory(prefix="neurochain-spice-") as tmp:
        work = Path(tmp)
        (work / "circuit.cir").write_text(netlist)
        result = subprocess.run(
            [NGSPICE, "-b", "circuit.cir"],
            cwd=work,
            capture_output=True,
            text=True,
            timeout=300,
            check=False,
        )
        log = result.stdout + result.stderr
        missing = [name for name in files if not (work / name).is_file()]
        if result.returncode != 0 or missing:
            raise SpiceError(f"ngspice failed (missing output: {missing}):\n{log[-2000:]}")
        tables = {
            name: np.atleast_2d(np.loadtxt(work / name, skiprows=1)).astype(np.float64)
            for name in files
        }
    return tables, log


def simulate_impedance(
    electrode: Electrode,
    *,
    start_hz: float = 1.0,
    stop_hz: float = 1.0e4,
    points_per_decade: int = 20,
) -> tuple[FloatArray, ComplexArray]:
    """Sweep an electrode's impedance in ngspice.

    Returns:
        ``(freqs_hz, impedance_ohm)``.
    """
    netlist = impedance_netlist(
        electrode, start_hz=start_hz, stop_hz=stop_hz, points_per_decade=points_per_decade
    )
    tables, _ = run_ngspice(netlist, (IMPEDANCE_FILE,))
    table = tables[IMPEDANCE_FILE]
    return table[:, 0], np.asarray(table[:, 1] + 1j * table[:, 2], dtype=np.complex128)


@dataclass(frozen=True)
class SpiceFrontEnd:
    """ngspice results for the electrode and amplifier.

    Attributes:
        ac_freqs_hz: Frequencies of the AC sweep.
        gain: Complex gain from tissue signal to output at those frequencies.
        noise_freqs_hz: Frequencies of the noise analysis.
        input_noise_asd: Input-referred noise density, V/√Hz.
        output_noise_asd: Output noise density, V/√Hz.
        input_noise_total_v: Input-referred noise integrated over the noise
            band by ngspice, volts RMS.
        output_noise_total_v: Output noise integrated over the noise band.
    """

    ac_freqs_hz: FloatArray
    gain: ComplexArray
    noise_freqs_hz: FloatArray
    input_noise_asd: FloatArray
    output_noise_asd: FloatArray
    input_noise_total_v: float
    output_noise_total_v: float

    def gain_at(self, freq_hz: float) -> float:
        """Return the gain magnitude at a frequency, interpolated on a log axis."""
        return float(np.interp(np.log(freq_hz), np.log(self.ac_freqs_hz), np.abs(self.gain)))

    def corner_hz(self, *, upper: bool) -> float:
        """Return the -3 dB frequency above or below the gain peak."""
        magnitude = np.abs(self.gain)
        peak = int(np.argmax(magnitude))
        target = magnitude[peak] / np.sqrt(2.0)
        if upper:
            f, m = self.ac_freqs_hz[peak:], magnitude[peak:]
        else:
            f, m = self.ac_freqs_hz[peak::-1], magnitude[peak::-1]
        below = int(np.argmax(m < target))
        # Linear interpolation in log-log space between the bracketing points.
        slope = (np.log(m[below]) - np.log(m[below - 1])) / (
            np.log(f[below]) - np.log(f[below - 1])
        )
        return float(np.exp(np.log(f[below - 1]) + (np.log(target) - np.log(m[below - 1])) / slope))


def _total(log: str, name: str) -> float:
    match = re.search(rf"{name}\s*=\s*([-+0-9.eE]+)", log)
    if match is None:
        raise SpiceError(f"ngspice did not report {name}:\n{log[-2000:]}")
    return float(match.group(1))


def simulate_frontend(
    frontend: FrontEnd,
    *,
    sources: NoiseSources = "all",
    noise_band_hz: tuple[float, float] = SPIKE_BAND_HZ,
) -> SpiceFrontEnd:
    """Run the AC sweep and the noise analysis of a front end in ngspice."""
    netlist = frontend_netlist(frontend, sources=sources, noise_band_hz=noise_band_hz)
    tables, log = run_ngspice(netlist, (AC_FILE, NOISE_FILE))
    ac, noise = tables[AC_FILE], tables[NOISE_FILE]
    return SpiceFrontEnd(
        ac_freqs_hz=ac[:, 0],
        gain=np.asarray(ac[:, 1] + 1j * ac[:, 2], dtype=np.complex128),
        noise_freqs_hz=noise[:, 0],
        input_noise_asd=noise[:, 1],
        output_noise_asd=noise[:, 2],
        input_noise_total_v=_total(log, "inoise_total"),
        output_noise_total_v=_total(log, "onoise_total"),
    )


def reference_netlists(frontend: FrontEnd) -> dict[str, str]:
    """Return the netlists kept under ``spice/``, keyed by file name.

    Raises:
        ValueError: If the front end has no electrode.
    """
    if frontend.electrode is None:
        raise ValueError("the reference netlists need an electrode")
    return {
        "electrode.cir": impedance_netlist(frontend.electrode.with_ideal_capacitor()),
        "electrode_cpe.cir": impedance_netlist(frontend.electrode),
        "frontend.cir": frontend_netlist(frontend),
    }
